import type { ReactNode } from 'react'

// Small inline SVG icons, so the app needs no icon library.
// They are drawn with currentColor, so an icon takes the text colour of whatever it sits in.

interface IconProps {
  size?: number
}

function Icon({ size = 18, children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {children}
    </svg>
  )
}

